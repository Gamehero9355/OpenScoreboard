/**
 * Radball view helpers -- pure functions over the tournament state, shared by
 * the competition overview, the dashboard, the operator screen and the print
 * views. The server remains the only source of truth: everything here reads
 * `state.radball` and never recalculates points, ranks or qualification.
 */
import type {
  Match,
  RadballCompetition,
  RadballGroup,
  RadballPhase,
  RadballPhaseKind,
  ShootoutState,
  StandingRow,
  TournamentState,
} from '../../shared/types';
import { isLiveMatchState } from '../../shared/matchUtils';
import { activeLocale, tr, type MessageKey } from './i18n';
import type { Translate } from '../../shared/matchUtils';

/**
 * A `t()` bound to one locale, threaded into the label helpers below.
 *
 * Optional by design. These are pure functions with callers that have no React
 * context at all -- the tests, and the print and bracket paths that build a label
 * table before a component exists -- so every one of them keeps the English
 * string it has always returned when no translator is supplied, and the screens
 * that render pass one in.
 */
/**
 * Re-exported rather than redeclared, so every locale-aware helper in
 * `src/frontend/lib` accepts the same translator. The catalogue's own
 * `MessageKey` still applies here -- only the `src/shared` helpers, which cannot
 * import it, take the looser signature.
 */
export type { Translate };

/**
 * `UCI_RADBALL_2025` -> `UCI Radball 2025`.
 *
 * The server stores ruleset versions and age classes as machine identifiers
 * because they have to round-trip through JSON and command payloads. The
 * conditions card is reference data a volunteer reads, so it gets the
 * identifier spoken back in words. Acronyms stay upper-case, the rest is
 * title-cased, and an unrecognised value is passed through untouched rather
 * than guessed at.
 */
const ACRONYMS = new Set(['UCI', 'BDR', 'U11', 'U13', 'U15', 'U17', 'U19', 'U23']);

function readableToken(value: string): string {
  return value
    .toLowerCase()
    .split(/[\s_-]+/)
    .filter(Boolean)
    .map((word) => {
      const upper = word.toUpperCase();
      if (ACRONYMS.has(upper)) return upper;
      // A year or a bare number keeps its digits and any U prefix.
      if (/^u?\d+$/i.test(word)) return upper;
      return word.charAt(0).toUpperCase() + word.slice(1);
    })
    .join(' ');
}

export function readableRuleset(rulesetVersion: string): string {
  return readableToken(rulesetVersion);
}

export function readableAgeClass(ageCategory: string): string {
  if (ageCategory === 'ELITE') return 'Elite';
  return readableToken(ageCategory);
}

/**
 * Human label for a competition phase kind.
 *
 * A function rather than a table because a table of strings cannot be
 * translated: this is called from module-level helpers that have no access to
 * React, so the caller passes a `t` and the lookup happens here.
 *
 * Every kind the catalogue names is translated; `round-robin` and `knockout`
 * are format names a host reads on the printed sheet, and they have entries of
 * their own here.
 */
export function phaseLabel(kind: RadballPhaseKind, t?: Translate): string {
  const say = t ?? tr;
  switch (kind) {
    case 'group-stage':
      return say('round.groupStage');
    case 'placement-round':
      return say('radball.phasePlacement');
    case 'decision':
      return say('radball.phaseDecision');
    case 'shootout':
      return say('radball.shootout');
    case 'final-round':
      return say('tree.finalRound');
    case 'round-robin':
      return say('radball.phaseRoundRobin');
    default:
      return say('radball.phaseKnockout');
  }
}

/**
 * The name of a phase, in the host's language.
 *
 * Phase names are generated by the engine and shown as panel and band titles
 * ("Preliminary round", "Group stage", "Final round"). The generated names are a
 * closed set, so they are translated; a name the engine did not generate is
 * passed through untouched rather than guessed at.
 */
export function phaseNameLabel(
  phase: { kind: RadballPhaseKind; name: string },
  t?: Translate,
): string {
  const known: Partial<Record<string, MessageKey>> = {
    'Preliminary round': 'radball10.preliminaryRound',
    'Group stage': 'round.groupStage',
    'Round robin': 'radball.phaseRoundRobin',
    'Final round': 'tree.finalRound',
    'Placement round': 'radball.phasePlacement',
    'Decision matches': 'radball.phaseDecision',
  };
  const key = known[phase.name];
  return key ? (t ?? tr)(key) : phase.name;
}

/**
 * A group's name in the host's language.
 *
 * The engine names the groups "Group A" and "Group B". Those two names are a
 * closed set, so they are translated; anything else is a name the host typed and
 * is passed through.
 */
export function groupNameLabel(name: string, t?: Translate): string {
  if (name === 'Group A') return (t ?? tr)('radball.groupA');
  if (name === 'Group B') return (t ?? tr)('radball.groupB');
  return name;
}

/** The generated round names the engine writes, as numbers. */
const PLACE_PAIR = /^(\d+)(?:st|nd|rd|th) \/ (\d+)(?:st|nd|rd|th) place$/;
const GROUP_ROUND = /^(.*?) · Round (\d+)$/;

/**
 * A round name in the host's language.
 *
 * Round names are generated by the engine ("Semifinals", "Round 3", "Group A ·
 * Round 5", "5th / 6th place") and shown on the schedule, the results and the
 * tree. The generated shapes are a closed set, so they are translated here; a
 * name that matches none of them is a name the host typed and stays as it is.
 *
 * The place pairs carry ordinals in English ("5th") and plain numbers in
 * German ("Platz 5 / 6"), so the number itself is what the catalogue receives.
 */
export function roundNameLabel(name: string, t?: Translate): string {
  const say = t ?? tr;
  const pair = PLACE_PAIR.exec(name);
  if (pair) {
    // English already says what the engine wrote ("5th / 6th place"); the German
    // wording needs the plain numbers, so it is built rather than translated.
    return activeLocale() === 'de'
      ? tr('roundName.placePair', { a: pair[1], b: pair[2] })
      : name;
  }
  const groupRound = GROUP_ROUND.exec(name);
  if (groupRound) {
    return say('roundName.groupRound', {
      group: groupRound[1] === 'Final Round' ? say('tree.finalRound') : groupNameLabel(groupRound[1], t),
      n: groupRound[2],
    });
  }
  const known: Partial<Record<string, MessageKey>> = {
    Final: 'round.final',
    Semifinals: 'radball10.stageSemifinals',
    Quarterfinals: 'roundName.quarterfinals',
    'Grand Final': 'roundName.grandFinal',
    'Grand Final Reset': 'roundName.grandFinalReset',
    '3rd Place Match': 'roundName.thirdPlaceMatch',
    'Semifinal 1': 'roundName.semifinal1',
    'Semifinal 2': 'roundName.semifinal2',
    'Radball Final': 'radball10.radballFinal',
    'Decision match': 'round.decision',
  };
  const key = known[name];
  if (key) return say(key);
  const round = /^Round (\d+)$/.exec(name);
  if (round) return say('round.roundOf', { n: round[1] });
  const losers = /^Losers Round (\d+)$/.exec(name);
  if (losers) return say('roundName.losersRound', { n: losers[1] });
  return name;
}

/** Short label for a match kind, used in queue rows and histories. */
export function matchKindLabel(kind: string | null | undefined, t?: Translate): string {
  const say = t ?? tr;
  switch (kind) {
    case 'group':
      return say('radball.kindGroup');
    case 'knockout':
      return say('radball.kindKnockout');
    case 'placement':
      return say('round.placement');
    case 'final':
      return say('round.final');
    case 'decision':
      return say('round.decision');
    default:
      return say('radball.kindMatch');
  }
}

/**
 * Readable text for a machine decision reason (CHAMPIONSHIP_TIE ...).
 *
 * The three reasons a tie can produce are carried whole by the catalogue; any
 * other reason is a machine enum this module has never seen and is passed
 * through spaced-out and lower-cased rather than guessed at.
 */
export function decisionReasonLabel(reason: string | null | undefined, t?: Translate): string {
  if (!reason) return '';
  const reasons: Record<string, MessageKey> = {
    CHAMPIONSHIP_TIE: 'radball.tieTitle',
    QUALIFICATION_TIE: 'radball.tieQualification',
    MANUAL: 'radball.tieManual',
  };
  const known = reasons[reason];
  if (known) return (t ?? tr)(known);
  return reason.replaceAll('_', ' ').toLowerCase();
}

export interface PhaseView {
  phase: RadballPhase;
  groups: RadballGroup[];
}

/** Phases in competition order with their groups resolved. */
export function phaseViews(competition: RadballCompetition): PhaseView[] {
  return competition.phaseOrder
    .map((id) => competition.phases[id])
    .filter((phase): phase is RadballPhase => Boolean(phase))
    .map((phase) => ({
      phase,
      groups: phase.groupIds.map((gid) => competition.groups[gid]).filter((g): g is RadballGroup => Boolean(g)),
    }));
}

/** All Radball matches of one group, in fixture order. */
export function groupMatches(state: TournamentState, groupId: string): Match[] {
  const rank = new Map(state.matchOrder.map((id, index) => [id, index]));
  return Object.values(state.matches)
    .filter((match) => match.radball?.groupId === groupId)
    .sort(
      (a, b) =>
        (rank.get(a.id) ?? Number.MAX_SAFE_INTEGER) - (rank.get(b.id) ?? Number.MAX_SAFE_INTEGER) ||
        a.round - b.round ||
        a.position - b.position,
    );
}

/** Every Radball match inside a phase (group fixtures, decisions, finals). */
export function phaseMatches(state: TournamentState, phaseId: string): Match[] {
  return Object.values(state.matches).filter((match) => match.radball?.phaseId === phaseId);
}

/**
 * True when a match is on a field right now.
 *
 * The clock state alone is not enough. Recording a point never moves a match
 * out of ASSIGNED -- `updateScore` only touches the score -- so a match whose
 * referee is calling goals can sit at ASSIGNED for its whole first half and only
 * reach RUNNING if someone presses start on the field screen. Testing the state
 * alone therefore filed a match that is visibly being played under "next up".
 *
 * Occupying a field is the condition the engine itself uses when it needs to
 * know what is in play (see `isOnField` and the field-occupancy checks in
 * `engine.ts` / `radball.ts`), so this follows the same rule.
 */
export function isOnNow(state: TournamentState, match: Match): boolean {
  if (isLiveMatchState(match.state)) return true;
  if (!match.fieldId) return false;
  return state.fields[match.fieldId]?.matchId === match.id;
}

/**
 * The whole competition as one list, first fixture to last.
 *
 * This is the order the competition is actually played in, which is *not* the
 * order the fixtures were created in. `state.matchOrder` records creation
 * order, and the generator emits group by group -- every round of group A, then
 * every round of group B. A multi-group event is run the other way around: all
 * groups play their first round together, then all their second rounds, because
 * the groups share the same fields and the same referees. So the sort leads with
 * the round, and only then falls back to the group.
 *
 * Phases lead everything, so a final round never appears before the group stage
 * it is fed by, and decision matches -- which the engine gives round 900 -- fall
 * at the end of their phase. Decided matches stay where they fell: "the
 * schedule" and "the results" are the same list read at different moments.
 */
export function competitionFixtures(state: TournamentState): Match[] {
  const competition = state.radball;
  const phaseRank = new Map((competition?.phaseOrder ?? []).map((id, index) => [id, index]));
  const groupRank = new Map((competition?.groupOrder ?? []).map((id, index) => [id, index]));
  // Creation order is the last resort, so two fixtures the rules leave equal
  // still come out in a stable, server-defined order.
  const creation = new Map(state.matchOrder.map((id, index) => [id, index]));

  const key = (match: Match): number[] => [
    phaseRank.get(match.radball?.phaseId ?? '') ?? Number.MAX_SAFE_INTEGER,
    match.round,
    groupRank.get(match.radball?.groupId ?? '') ?? Number.MAX_SAFE_INTEGER,
    match.position,
    creation.get(match.id) ?? Number.MAX_SAFE_INTEGER,
  ];

  return Object.values(state.matches)
    .filter((match) => match.radball !== null && match.state !== 'CANCELLED')
    .sort((a, b) => {
      const ka = key(a);
      const kb = key(b);
      for (let i = 0; i < ka.length; i += 1) {
        if (ka[i] !== kb[i]) return ka[i] - kb[i];
      }
      return 0;
    });
}

/**
 * How a fixture should read in the list: history, live on a field, the one to
 * call, or just part of the run of games.
 */
export type FixtureRole = 'done' | 'live' | 'call' | 'upcoming' | 'waiting';

/**
 * The list in the order the page shows it: what is on a field now, then the rest
 * of the competition in playing order.
 *
 * The playing order alone is not enough to be useful. A competition runs
 * round by round, so a match in the last round of a long group stage sits at the
 * very bottom of a purely chronological list -- which is exactly where a referee
 * looks first. Hoisting the matches that are on a field keeps the current state
 * of the tournament at the top without splitting the list into sections: it is
 * still one column, and the rest of it is still first game to last game.
 *
 * Only a handful of fixtures are ever hoisted (one per field), so the list stays
 * effectively chronological.
 */
export function fixturesForDisplay(state: TournamentState): Match[] {
  const fixtures = competitionFixtures(state);
  const live = fixtures.filter((match) => match.state !== 'FINISHED' && isOnNow(state, match));
  if (live.length === 0) return fixtures;
  const liveIds = new Set(live.map((match) => match.id));
  return [...live, ...fixtures.filter((match) => !liveIds.has(match.id))];
}

/**
 * The one match an organiser should send people to next: the first fixture in
 * order that is neither decided nor already on a field and has both sides.
 *
 * Scanning front to back is the point -- the matches on a field are skipped, so
 * the row to call is the next playable one behind them.
 */
export function nextFixtureToCall(state: TournamentState, fixtures: Match[]): string | null {
  for (const match of fixtures) {
    if (match.state === 'FINISHED') continue;
    if (isOnNow(state, match)) continue;
    if (!match.participantAId || !match.participantBId) continue;
    return match.id;
  }
  return null;
}

/**
 * Classify one fixture for display. A decided match is history even if it still
 * holds a field link, so `done` is tested first.
 */
export function fixtureRole(state: TournamentState, match: Match, callId: string | null): FixtureRole {
  if (match.state === 'FINISHED') return 'done';
  if (isOnNow(state, match)) return 'live';
  if (callId !== null && match.id === callId) return 'call';
  return match.participantAId && match.participantBId ? 'upcoming' : 'waiting';
}

/** Decision matches across the whole competition, newest first. */
export function decisionMatches(state: TournamentState): Match[] {
  return Object.values(state.matches)
    .filter((match) => match.radball?.kind === 'decision')
    .sort((a, b) => (b.radball?.decisionReason ? 1 : 0) - (a.radball?.decisionReason ? 1 : 0) || a.id.localeCompare(b.id));
}

/** Open (not finished, not cancelled) decision matches -- the ones to play. */
export function openDecisionMatches(state: TournamentState): Match[] {
  return decisionMatches(state).filter(
    (match) => match.state !== 'FINISHED' && match.state !== 'CANCELLED',
  );
}

/** True when the group stage (every entry-phase group) is fully played. */
export function groupStageComplete(state: TournamentState): boolean {
  const competition = state.radball;
  if (!competition) return false;
  const entryPhases = competition.phaseOrder
    .map((id) => competition.phases[id])
    .filter((phase) => phase?.kind === 'group-stage' || phase?.kind === 'round-robin');
  for (const phase of entryPhases) {
    for (const groupId of phase?.groupIds ?? []) {
      const done = Object.values(state.matches)
        .filter((match) => match.radball?.groupId === groupId && match.radball.kind === 'group')
        .every((match) => match.state === 'FINISHED' || match.state === 'CANCELLED');
      if (!done) return false;
    }
  }
  return entryPhases.length > 0;
}

/**
 * How much of a tournament has actually been played.
 *
 * This is deliberately not `computeResults().finishedMatches / totalMatches`.
 * That pair sizes the *draw*: it counts fixtures the engine created and later
 * cancelled once a tie was settled another way, so a finished tournament can
 * report 15/18 and a progress bar can never reach the end. A progress readout
 * has to converge on 100% when the last match is done, so cancelled matches
 * leave the denominator and only a real finish counts toward the numerator.
 *
 * Every masthead uses this one function, so the Competition and Results tabs
 * can never disagree about how far along the tournament is.
 */
export function competitionProgress(state: TournamentState): { finished: number; total: number } {
  let finished = 0;
  let total = 0;
  for (const match of Object.values(state.matches)) {
    if (match.state === 'CANCELLED') continue;
    total += 1;
    if (match.state === 'FINISHED') finished += 1;
  }
  return { finished, total };
}

/** Shootout tally: hits per side plus the thrown attempts. */
export function shootoutScore(
  shootout: ShootoutState | null | undefined,
): { a: { hits: number; thrown: number }; b: { hits: number; thrown: number } } {
  const tally = { a: { hits: 0, thrown: 0 }, b: { hits: 0, thrown: 0 } };
  if (!shootout) return tally;
  for (const attempt of shootout.attempts) {
    const side = attempt.side === 'A' ? tally.a : tally.b;
    side.thrown += 1;
    if (attempt.hit) side.hits += 1;
  }
  return tally;
}

/** Which side throws the next shootout attempt (A always opens). */
export function nextShootoutSide(shootout: ShootoutState | null | undefined): 'A' | 'B' {
  if (!shootout) return 'A';
  return shootout.attempts.length % 2 === 0 ? 'A' : 'B';
}

/** True when regulation (attemptsPerTeam per side) is fully thrown. */
export function shootoutRegulationDone(shootout: ShootoutState): boolean {
  const score = shootoutScore(shootout);
  return score.a.thrown >= shootout.attemptsPerTeam && score.b.thrown >= shootout.attemptsPerTeam;
}

/**
 * Status text for a standings row, colour-independent (mark plus label).
 *
 * Every status a standings row can carry reads in the host's language; the
 * German wording is the one a hall uses for "through" and "out".
 */
export function standingStatusLabel(row: StandingRow, t?: Translate): string {
  const say = t ?? tr;
  switch (row.status) {
    case 'qualified':
      return say('results.advances');
    case 'playoff':
      return say('radball.statusPlayoff');
    case 'tied':
      return row.note ?? say('radball.statusDecisionRequired');
    case 'open':
      return say('radball.statusLiveTable');
    case 'eliminated':
      return say('results.out');
    default:
      return '';
  }
}

/**
 * The overall competition status line for the overview page:
 * what phase is running and what the operators should look at next.
 */
export function competitionHint(state: TournamentState): string | null {
  const competition = state.radball;
  if (!competition) return null;
  const openDecisions = openDecisionMatches(state);
  if (openDecisions.length > 0) {
    return `Decision match required: ${openDecisions
      .map((match) => `${nameOf(state, match.participantAId)} vs ${nameOf(state, match.participantBId)}`)
      .join(', ')}`;
  }
  if (competition.championId) {
    return `Champion: ${nameOf(state, competition.championId)}`;
  }
  return null;
}

function nameOf(state: TournamentState, id: string | null): string {
  if (!id) return 'TBD';
  return state.participants[id]?.name ?? 'Unknown';
}
