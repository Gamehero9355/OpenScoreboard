/**
 * Language catalogue.
 *
 * English and German, because the domain is German: Radball is a BDR-run sport,
 * the age classes are `U11`..`ELITE`, and the clubs are `RV <Ort> I/II`. A host
 * running a `BDR Deutsche Meisterschaft` is reading a German app with English
 * labels on it today, and "Undo"/"Correct score" is not what a volunteer calls
 * those buttons.
 *
 * Shape and rules:
 *
 *  - **One flat record per language**, keys are dotted paths (`nav.host`), so a
 *    missing translation is one `grep` away rather than a hunt through nested
 *    objects.
 *  - **English is the source of truth.** `Messages` is derived from `en`, so a
 *    key that exists only in German is a compile error rather than a silent
 *    blank on screen.
 *  - **No runtime framework, nothing fetched.** Every string ships in the
 *    bundle, which is what the offline-first promise requires -- an i18n library
 *    that pulls a locale file over the network would break it outright.
 *  - **`{name}` placeholders**, not a formatter library. Substituting one value
 *    into one string is all this app ever does.
 *  - **Brand terms stay put.** `Radball`, `RV <Ort>`, `U11`..`ELITE`, `BDR` and
 *    the ruleset ids are proper nouns; translating them would make the app
 *    disagree with the paperwork the host is holding.
 *  - **The engine's own sentences are here too.** Activity log lines and toasts
 *    are written by the server, so their English lives in
 *    `src/shared/eventMessages.ts` and is spread into `en` below; the German
 *    for each one sits in this file like every other string, which is what
 *    makes "the activity feed is still English" a failing test rather than a
 *    complaint.
 */
