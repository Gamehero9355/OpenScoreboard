/* Runtime                                                             */
/* ------------------------------------------------------------------ */

/** Values substituted into a `{placeholder}`. */
export type MessageParams = Record<string, string | number>;

/** Coerce anything the app might hold into a supported locale. */
export function normaliseLocale(value: unknown): Locale {
  return value === 'de' ? 'de' : DEFAULT_LOCALE;
}

/**
 * Look up `key` in `locale`, substituting any `{placeholder}` values.
 *
 * Two deliberate fallbacks, both aimed at a hall rather than at a test:
 *
 *  - A key missing from German falls back to the English string rather than
 *    rendering the raw key. A half-translated screen is understandable; a wall
 *    of `settings.backupHint` is not.
 *  - A placeholder the caller forgot to pass is left in place, so the missing
 *    value is visible in the string itself instead of silently vanishing.
 */
export function translate(
  locale: Locale,
  key: MessageKey,
  params?: MessageParams,
): string {
  const template = MESSAGES[locale][key] ?? en[key];
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) => {
    const value = params[name];
    return value === undefined || value === null ? match : String(value);
  });
}

/**
 * The locale in use outside a React render.
 *
 * `useI18n` writes it whenever the active language changes. Module-level code
 * has no hook to read: `live`'s toast text, and the round titles and standings
 * headings the bracket builders *generate* rather than render. Threading a
 * locale through every builder would put a display concern in the middle of the
 * bracket maths, and the builders are also called from `src/shared` and the
 * server-side engine where a locale does not exist at all.
 *
 * Defaults to English, which is what a test run and a plain Node import see, so
 * pure functions keep returning the strings their tests assert.
 */
let active: Locale = DEFAULT_LOCALE;

export function setActiveLocale(locale: Locale): void {
  active = normaliseLocale(locale);
}

export function activeLocale(): Locale {
  return active;
}

/**
 * `translate` against the active locale, for code that cannot call a hook.
 *
 * Keys, not sentences: a `tr('round.final')` in a builder is still one grep away
 * from its German, exactly like a `t()` in a component.
 */
export function tr(key: MessageKey, params?: MessageParams): string {
  return translate(active, key, params);
}

/**
 * Is `key` in the catalogue?
 *
 * For callers holding a key from *outside* the app -- a stored activity line,
 * a notice from the server -- where the type system cannot promise anything.
 * `translate` would return `undefined` for an unknown key, so the caller needs
 * to ask first and fall back to the wording the server sent with it.
 */
export function hasMessage(key: string): key is MessageKey {
  return Object.prototype.hasOwnProperty.call(en, key);
}

/**
 * The first available `Intl` tag for a locale.
 *
 * Prefers the exact tag (`de-DE`) and falls back to the base language (`de`), so
 * a runtime without full ICU data still formats dates and numbers correctly
 * instead of throwing. A venue laptop with a trimmed Node build is exactly the
 * case that matters here.
 */
export function intlTag(locale: Locale, kind: 'date' | 'time' | 'number'): string {
  const exact = INTL_TAG[locale];
  const base = locale;
  for (const tag of [exact, base]) {
    try {
      if (kind === 'date') new Intl.DateTimeFormat(tag).format(new Date(0));
      else if (kind === 'time') new Intl.DateTimeFormat(tag, { timeStyle: 'short' }).format(new Date(0));
      else new Intl.NumberFormat(tag).format(1);
      return tag;
    } catch {
      /* try the next tag */
    }
  }
  return locale;
}

/** A short date and time, in the venue's own format. */
export function formatDateTime(locale: Locale, timestamp: number): string {
  try {
    return new Intl.DateTimeFormat(intlTag(locale, 'date'), {
      dateStyle: 'medium',
      timeStyle: 'short',
    }).format(new Date(timestamp));
  } catch {
    return new Date(timestamp).toISOString();
  }
}

/** A time of day, in the venue's own format. */
export function formatTime(locale: Locale, timestamp: number): string {
  try {
    return new Intl.DateTimeFormat(intlTag(locale, 'time'), { timeStyle: 'short' }).format(new Date(timestamp));
  } catch {
    return new Date(timestamp).toISOString();
  }
}

/**
 * Every key present in English but missing from German.
 *
 * Exported so a test can assert the catalogue stays complete: a language that
 * quietly falls back is a language nobody notices is unfinished.
 */
export function missingKeys(locale: Locale): MessageKey[] {
  const target = MESSAGES[locale];
  return (Object.keys(en) as MessageKey[]).filter((key) => !target[key]);
}

/** Keys whose two languages differ, for review tooling and tests. */
export function translatedKeyCount(locale: Locale): number {
  return (Object.keys(en) as MessageKey[]).filter((key) => MESSAGES[locale][key] !== en[key]).length;
}
